"""Generate 16-bit pixel art sprites for normGym grid rendering.

Each sprite is drawn at 16x16 (cells) or 12x12 (agents) using palette-indexed
pixel grids, then scaled up with nearest-neighbor resampling to preserve the
crisp retro look.
"""

