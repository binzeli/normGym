def _darken(color, factor):
    """Darken an RGB tuple by a factor (0.0 = black, 1.0 = unchanged)."""
    r, g, b = color
    return (int(r * factor), int(g * factor), int(b * factor))


def _lighten(color, factor):
    """Lighten an RGB tuple toward white by factor (0.0 = unchanged, 1.0 = white)."""
    r, g, b = color
    return (int(r + (255 - r) * factor), int(g + (255 - g) * factor), int(b + (255 - b) * factor))


def _rgba(color, alpha=255):
    """Convert an RGB tuple to RGBA."""
    return color + (alpha,)


def draw_iso_floor_tile(palette, tile_w=80, tile_h=40):
    """Draw a clean solid-color diamond floor tile with subtle plank lines."""
    img = Image.new("RGBA", (tile_w, tile_h), (0, 0, 0, 0))
    draw = ImageDraw.Draw(img)
    cx, cy = tile_w // 2, tile_h // 2

    diamond = [(cx, 0), (tile_w - 1, cy), (cx, tile_h - 1), (0, cy)]
    outline_color = palette[1] if len(palette) > 1 else _darken(palette[0], 0.7)
    draw.polygon(diamond, fill=_rgba(palette[0]), outline=_rgba(outline_color))

    # Subtle plank accent lines
    accent = (palette[1] if len(palette) > 1 else _darken(palette[0], 0.85))
    overlay = Image.new("RGBA", (tile_w, tile_h), (0, 0, 0, 0))
    ov_draw = ImageDraw.Draw(overlay)
    for frac in [0.33, 0.66]:
        y = int(tile_h * frac)
        dist = abs(y - cy)
        hw = int((1.0 - dist / cy) * cx) if cy > 0 else 0
        if hw > 2:
            ov_draw.line([(cx - hw + 2, y), (cx + hw - 2, y)], fill=_rgba(accent, 80), width=1)
    img = Image.alpha_composite(img, overlay)
    return img


def _draw_base_block(draw, palette, tile_w, tile_h, extrusion,
                     top_color=None, left_color=None, right_color=None, outline_color=None):
    """Draw the base three-face iso block. Returns (top_diamond, left_face, right_face) polygons."""
    cx, cy = tile_w // 2, tile_h // 2
    base = palette[0]
    ol = outline_color or (palette[1] if len(palette) > 1 else _darken(base, 0.6))
    tc = top_color or base
    lc = left_color or _darken(base, 0.65)
    rc = right_color or _darken(base, 0.50)

    left_face = [(0, cy), (cx, tile_h - 1), (cx, tile_h - 1 + extrusion), (0, cy + extrusion)]
    right_face = [(cx, tile_h - 1), (tile_w - 1, cy), (tile_w - 1, cy + extrusion), (cx, tile_h - 1 + extrusion)]
    top_diamond = [(cx, 0), (tile_w - 1, cy), (cx, tile_h - 1), (0, cy)]

    draw.polygon(left_face, fill=_rgba(lc), outline=_rgba(ol))
    draw.polygon(right_face, fill=_rgba(rc), outline=_rgba(ol))
    draw.polygon(top_diamond, fill=_rgba(tc), outline=_rgba(ol))

    return top_diamond, left_face, right_face


def _draw_slab(draw, tw, th, y_offset, slab_ext, color, outline,
               inset=0.0, left_dark=0.65, right_dark=0.50):
    """Draw a thin iso slab (tabletop, seat, shelf board) at a given y_offset.

    The slab is a thin block sitting at y_offset pixels below the standard
    top diamond position. inset (0.0-0.5) shrinks the diamond inward.
    """
    cx, cy = tw // 2, th // 2
    # Inset diamond vertices
    i = inset
    top = _top_face_point(cx, cy, tw, th, i, i)
    right = _top_face_point(cx, cy, tw, th, 1 - i, i)
    bottom = _top_face_point(cx, cy, tw, th, 1 - i, 1 - i)
    left = _top_face_point(cx, cy, tw, th, i, 1 - i)
    # Shift down by y_offset
    top = (top[0], top[1] + y_offset)
    right = (right[0], right[1] + y_offset)
    bottom = (bottom[0], bottom[1] + y_offset)
    left = (left[0], left[1] + y_offset)

    lc = _darken(color, left_dark)
    rc = _darken(color, right_dark)
    ol = _rgba(outline)

    # Left face
    draw.polygon([left, bottom,
                  (bottom[0], bottom[1] + slab_ext),
                  (left[0], left[1] + slab_ext)],
                 fill=_rgba(lc), outline=ol)
    # Right face
    draw.polygon([bottom, right,
                  (right[0], right[1] + slab_ext),
                  (bottom[0], bottom[1] + slab_ext)],
                 fill=_rgba(rc), outline=ol)
    # Top face
    draw.polygon([top, right, bottom, left], fill=_rgba(color), outline=ol)

    return top, right, bottom, left


def _draw_iso_leg(draw, x, y_top, leg_height, color, outline, width=3):
    """Draw a single isometric leg (vertical column) at screen position (x, y_top)."""
    # A leg in iso is a tiny vertical parallelogram
    hw = width // 2
    ol = _rgba(outline)
    lc = _rgba(_darken(color, 0.5))
    rc = _rgba(_darken(color, 0.35))
    fc = _rgba(color)
    y_bot = y_top + leg_height
    # Front face (right side of leg)
    draw.polygon([(x, y_top), (x + hw, y_top),
                  (x + hw, y_bot), (x, y_bot)], fill=rc, outline=ol)
    # Left face of leg
    draw.polygon([(x - hw, y_top), (x, y_top),
                  (x, y_bot), (x - hw, y_bot)], fill=lc, outline=ol)
    # Top of leg
    draw.rectangle([(x - hw, y_top - 1), (x + hw, y_top)], fill=fc)


def _left_face_line(draw, tile_w, tile_h, extrusion, frac, color, width=1):
    """Draw a horizontal line across the left face at frac (0=top, 1=bottom) of extrusion."""
    cx, cy = tile_w // 2, tile_h // 2
    y_left = int(cy + frac * extrusion)
    y_right = int(tile_h - 1 + frac * extrusion)
    draw.line([(1, y_left), (cx - 1, y_right)], fill=color, width=width)


def _right_face_line(draw, tile_w, tile_h, extrusion, frac, color, width=1):
    """Draw a horizontal line across the right face at frac (0=top, 1=bottom) of extrusion."""
    cx, cy = tile_w // 2, tile_h // 2
    y_left = int(tile_h - 1 + frac * extrusion)
    y_right = int(cy + frac * extrusion)
    draw.line([(cx + 1, y_left), (tile_w - 2, y_right)], fill=color, width=width)


def _left_face_vline(draw, tile_w, tile_h, extrusion, frac_x, color, width=1):
    """Draw a vertical line on the left face at frac_x (0=left edge, 1=right edge)."""
    cx, cy = tile_w // 2, tile_h // 2
    x = int(frac_x * cx)
    y_top = int(cy + (tile_h - 1 - cy) * frac_x)
    y_bot = y_top + extrusion
    draw.line([(x, y_top), (x, y_bot)], fill=color, width=width)


def _right_face_vline(draw, tile_w, tile_h, extrusion, frac_x, color, width=1):
    """Draw a vertical line on the right face at frac_x (0=left edge, 1=right edge)."""
    cx, cy = tile_w // 2, tile_h // 2
    x = int(cx + frac_x * (tile_w - 1 - cx))
    y_top = int((tile_h - 1) + (cy - tile_h + 1) * frac_x)
    y_bot = y_top + extrusion
    draw.line([(x, y_top), (x, y_bot)], fill=color, width=width)


def _top_face_point(cx, cy, tile_w, tile_h, u, v):
    """Map (u,v) in [0,1]x[0,1] to a point on the top diamond face.
    u=0,v=0 is the top vertex; u=1,v=0 is right; u=0,v=1 is left; u=1,v=1 is bottom."""
    # Four vertices: top(cx,0), right(tw-1,cy), bottom(cx,th-1), left(0,cy)
    tw, th = tile_w, tile_h
    # Bilinear interpolation on diamond
    top = (cx, 0)
    right = (tw - 1, cy)
    bottom = (cx, th - 1)
    left = (0, cy)
    # Interpolate: top-right edge at u, top-left edge at u
    tr_x = top[0] + (right[0] - top[0]) * u
    tr_y = top[1] + (right[1] - top[1]) * u
    bl_x = left[0] + (bottom[0] - left[0]) * u
    bl_y = left[1] + (bottom[1] - left[1]) * u
    x = tr_x + (bl_x - tr_x) * v
    y = tr_y + (bl_y - tr_y) * v
    return int(x), int(y)


