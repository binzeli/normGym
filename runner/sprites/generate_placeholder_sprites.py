def _agent_state_overlay(state, out_size):
    """Draw the top-down-style state indicator on a transparent out_size canvas:
    a speech bubble (order), a green check badge (done) or a red '!' badge
    (push), all at the top-right. Returns None for states with no overlay."""
    if state not in ('order', 'done', 'push'):
        return None
    SS = 4
    C = 64
    a = Image.new("RGBA", (C * SS, C * SS), (0, 0, 0, 0))
    dd = ImageDraw.Draw(a)
    OUT = (40, 32, 38, 255)
    W = (255, 255, 255, 255)
    if state == 'order':
        dot = (70, 70, 78, 255)
        dd.rounded_rectangle([36 * SS, 0, 64 * SS - 1, 18 * SS], radius=7 * SS,
                             fill=W, outline=OUT, width=2 * SS)
        dd.polygon([(43 * SS, 15 * SS), (50 * SS, 15 * SS), (41 * SS, 24 * SS)],
                   fill=W, outline=OUT, width=SS)
        for x in (44, 51, 58):
            dd.ellipse([(x - 2.6) * SS, 6 * SS, (x + 2.6) * SS, 13 * SS], fill=dot)
    elif state == 'done':
        dd.ellipse([43 * SS, 0, 63 * SS, 20 * SS], fill=(92, 194, 92, 255),
                   outline=(38, 120, 50, 255), width=2 * SS)
        dd.pieslice([46 * SS, 2 * SS, 60 * SS, 12 * SS], 190, 350,
                    fill=(155, 226, 155, 255))
        dd.line([(47 * SS, 10 * SS), (52 * SS, 15 * SS), (61 * SS, 2 * SS)],
                fill=W, width=4 * SS, joint='curve')
    else:  # push -- red '!' badge
        dd.ellipse([46 * SS, 0, 64 * SS - 1, 18 * SS], fill=(228, 72, 72, 255),
                   outline=(150, 30, 30, 255), width=2 * SS)
        dd.rounded_rectangle([53 * SS, 3 * SS, 57 * SS, 11 * SS], radius=2 * SS, fill=W)
        dd.ellipse([53 * SS, 13 * SS, 57 * SS, 17 * SS], fill=W)
    return a.resize((out_size, out_size), Image.LANCZOS)


def _draw_creature(body, out_size):
    """Draw a chunky low-res pixel creature (round blob body, pointy cat ears,
    small dot eyes, tiny arms and feet, lighter belly) in `body` color.

    Drawn at a small native resolution with no anti-aliasing, then scaled up
    with NEAREST so it keeps a blocky, retro pixel-art look.
    """
    def dark(c, f):
        return tuple(max(0, min(255, int(v * f))) for v in c[:3])

    def light(c, f):
        return tuple(max(0, min(255, int(v + (255 - v) * f))) for v in c[:3])

    def A(c):
        return (c[0], c[1], c[2], 255)

    R = 22
    img = Image.new("RGBA", (R, R), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    BODY = A(body)
    OUT = A(dark(body, 0.42))
    BELLY = A(light(body, 0.42))
    EYE = (46, 40, 46, 255)

    # ears (behind body)
    d.polygon([(5, 7), (3, 1), (10, 6)], fill=BODY, outline=OUT)
    d.polygon([(16, 7), (18, 1), (11, 6)], fill=BODY, outline=OUT)
    # arms
    d.ellipse([1, 11, 6, 17], fill=BODY, outline=OUT)
    d.ellipse([15, 11, 20, 17], fill=BODY, outline=OUT)
    # feet
    d.ellipse([5, 15, 10, 21], fill=BODY, outline=OUT)
    d.ellipse([11, 15, 16, 21], fill=BODY, outline=OUT)
    # body blob
    d.ellipse([3, 5, 18, 19], fill=BODY, outline=OUT)
    # belly
    d.ellipse([7, 10, 14, 18], fill=BELLY)
    # eyes (two small dots)
    d.rectangle([8, 10, 9, 11], fill=EYE)
    d.rectangle([12, 10, 13, 11], fill=EYE)
    return img.resize((out_size, out_size), Image.NEAREST)


def make_pixel_agent(body, shape='circle', state='normal', out_size=32):
    """Draw an agent (``creature`` or an abstract circle / square / triangle)
    in `body` color and scale to out_size.

    The shape and color encode the agent's strength; the ``state`` adds a
    top-down-style indicator on top: ``order`` a speech bubble, ``done`` a green
    check badge, ``push`` a red '!' badge. ``normal`` is the plain agent.

    body: (r, g, b) fill color. The outline / highlight / eye tones are derived
          from it so any color reads cleanly.
    """
    if shape == 'creature':
        img = _draw_creature(body, out_size)
        overlay = _agent_state_overlay(state, out_size)
        if overlay is not None:
            img = Image.alpha_composite(img, overlay)
        return img

    def dark(c, f):
        return tuple(max(0, min(255, int(v * f))) for v in c[:3])

    def light(c, f):
        return tuple(max(0, min(255, int(v + (255 - v) * f))) for v in c[:3])

    palette = [tuple(body), dark(body, 0.30), light(body, 0.50), dark(body, 0.28)]
    grid = AGENT_SHAPE_GRIDS.get(shape, AGENT_SHAPE_GRIDS['circle'])

    base = Image.new("RGBA", (16, 16), (0, 0, 0, 0))
    for y, row in enumerate(grid):
        for x, idx in enumerate(row):
            if idx is None:
                continue
            r, g, b = palette[idx]
            base.putpixel((x, y), (r, g, b, 255))
    img = base.resize((out_size, out_size), Image.NEAREST)

    overlay = _agent_state_overlay(state, out_size)
    if overlay is not None:
        img = Image.alpha_composite(img, overlay)
    return img


