def main():
    print(f"Generating pixel art sprites in {ASSETS_DIR}/")

    # Cell sprites (16x16 -> 64x64)
    for subdir, filename, palette, px_grid in CELL_DEFS:
        dirpath = os.path.join(ASSETS_DIR, subdir)
        os.makedirs(dirpath, exist_ok=True)
        filepath = os.path.join(dirpath, filename)
        img = pixels_to_image(px_grid, palette, out_size=64)
        img.save(filepath)
        print(f"  Created {os.path.relpath(filepath, ROOT)}")

    # Agent sprites (12x12 -> 48x48)
    agents_dir = os.path.join(ASSETS_DIR, "agents")
    os.makedirs(agents_dir, exist_ok=True)
    for strength, color in STRENGTH_COLORS.items():
        for state in AGENT_STATES:
            filename = f"strength_{strength}{'_' + state if state != 'normal' else ''}.png"
            filepath = os.path.join(agents_dir, filename)
            img = make_pixel_agent(color, shape=STRENGTH_SHAPES[strength],
                                   state=state, out_size=32)
            img.save(filepath)
            print(f"  Created {os.path.relpath(filepath, ROOT)}")

    # LLM star (8x8 -> 24x24)
    star = make_pixel_star(px_size=8, out_size=24)
    star_path = os.path.join(agents_dir, "llm_star.png")
    star.save(star_path)
    print(f"  Created {os.path.relpath(star_path, ROOT)}")

    # Floor tile (16x16 -> 64x64)
    floor_dir = os.path.join(ASSETS_DIR, "floor")
    os.makedirs(floor_dir, exist_ok=True)
    floor_path = os.path.join(floor_dir, "wood_tile.png")
    tile = pixels_to_image(FLOOR_PX, FLOOR_PAL, out_size=64)
    tile.save(floor_path)
    print(f"  Created {os.path.relpath(floor_path, ROOT)}")

    num_agents = len(STRENGTH_COLORS) * len(AGENT_STATES)
    total = len(CELL_DEFS) + num_agents + 2  # +2 for star and floor

    # === Isometric sprites ===
    print("\nGenerating isometric sprites...")
    iso_count = 0

    # Iso cell sprites
    for subdir, filename, palette, px_grid in CELL_DEFS:
        iso_subdir = os.path.join("iso", subdir)
        dirpath = os.path.join(ASSETS_DIR, iso_subdir)
        os.makedirs(dirpath, exist_ok=True)
        filepath = os.path.join(dirpath, filename)
        stem = os.path.splitext(filename)[0]
        ext_h = EXTRUSION_MAP.get(stem, 0)
        img = draw_iso_sprite(stem, palette, tile_w=80, tile_h=40, extrusion=ext_h)
        img.save(filepath)
        iso_count += 1
        print(f"  Created iso {os.path.relpath(filepath, ROOT)}")

    # Iso floor tile
    iso_floor_dir = os.path.join(ASSETS_DIR, "iso", "floor")
    os.makedirs(iso_floor_dir, exist_ok=True)
    iso_floor_path = os.path.join(iso_floor_dir, "wood_tile.png")
    iso_floor = draw_iso_floor_tile(FLOOR_PAL, tile_w=80, tile_h=40)
    iso_floor.save(iso_floor_path)
    iso_count += 1
    print(f"  Created iso {os.path.relpath(iso_floor_path, ROOT)}")

    # Iso agent sprites (billboard — just resize, keep upright)
    iso_agents_dir = os.path.join(ASSETS_DIR, "iso", "agents")
    os.makedirs(iso_agents_dir, exist_ok=True)
    for strength, color in STRENGTH_COLORS.items():
        for state in AGENT_STATES:
            filename = f"strength_{strength}{'_' + state if state != 'normal' else ''}.png"
            filepath = os.path.join(iso_agents_dir, filename)
            img = make_pixel_agent(color, shape=STRENGTH_SHAPES[strength],
                                   state=state, out_size=40)
            img.save(filepath)
            iso_count += 1
            print(f"  Created iso {os.path.relpath(filepath, ROOT)}")

    # Iso LLM star
    iso_star = make_pixel_star(px_size=8, out_size=20)
    iso_star_path = os.path.join(iso_agents_dir, "llm_star.png")
    iso_star.save(iso_star_path)
    iso_count += 1
    print(f"  Created iso {os.path.relpath(iso_star_path, ROOT)}")

    print(f"\nDone! Generated {total} flat sprites + {iso_count} isometric sprites.")


if __name__ == "__main__":
    main()
